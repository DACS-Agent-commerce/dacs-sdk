// Two parties never share a clock. A signer stamps expiresAt (or notBefore)
// from its own clock and the receiver compares it with another, so every such
// rule leaves DACS_SELLER_HTTP_LIMITS.maxClockSkewMs of room: signers give at
// most maxSignedLifetimeMs (30 s), receivers accept up to maxMessageLifetimeMs
// (60 s), and a journal keeps a reservation until retainUntil. The same
// retained-state rule binds a direct request to the host's artifacts.
import { createHash, generateKeyPairSync, sign } from "node:crypto";
import { describe, expect, it, vi } from "vitest";

import { canonicalize } from "../../src/canonical/index.js";
import {
  checkWireRequest, DACS_SELLER_HTTP_LIMITS, openWireEnvelope, signWireResponse, verifyWireResponse,
  WireError, type RequestCheck, type WireRequestPayload, type WireRequestReservation, type WireSigner,
} from "../../src/wire/index.js";
// SYNTHETIC records are approved only by replacing src/wire/approval.ts with a
// test list (./testApproval.ts); no shipped module takes an approval list.
vi.mock("../../src/wire/approval.js", () => import("./testApproval.js"));
import { withTestApproval } from "./testApproval.js";

const bindTp1Fixture = fixtureBinder(fixtureWire);

const NOW = Date.UTC(2026, 9, 14, 12, 0, 0);
const JOB = "01K7FZ8Q9W3V5T2R1N0M8K6J4H";
const OTHER_JOB = "01K7FZ8Q9W3V5T2R1N0M8K6J4J";
const PIN = { listingId: "clock-skew-report", version: 1, contentHash: "c".repeat(64) };
const AGREEMENT = "a".repeat(64);
const RPC_A = { endpoint: "https://rpc-a.clock-skew.invalid/", transportAuthority: "test-a", connectionId: "a-1" };
const RPC_B = { endpoint: "https://rpc-b.clock-skew.invalid/", transportAuthority: "test-b", connectionId: "b-1" };
const TEXT = `{"jobId":"${JOB}"}`;
const ANSWER = '{"status":"committed"}';
const sha = (v: string) => createHash("sha256").update(v).digest("hex");

function party(): WireSigner & { raw: string } {
  const { privateKey, publicKey } = generateKeyPairSync("ed25519");
  const raw = publicKey.export({ format: "der", type: "spki" }).subarray(-32).toString("hex");
  const signer = { claim: `did:demos:agent:${raw}`, sign: (bytes: Uint8Array) => new Uint8Array(sign(null, Buffer.from(bytes), privateKey)) };
  registerDiscoverySigner(signer);
  return { ...signer, raw };
}

/** SYNTHETIC test-only identity record; not the approved record, not a Demos chain identity. */
function world() {
  const buyer = party(), seller = party(), session = party(), other = party();
  const record = {
    format: "dacs-testnet-identity-record/v1", recordId: "synthetic-test-only/clock-skew", network: "demos-testnet",
    chainIdentity: sha(`SYNTHETIC/clock-skew/${Math.random()}`), pinVersion: "synthetic-test-only/1",
    provenance: { approvedBy: "SYNTHETIC test", approvedAt: "2026-10-14T12:00:00.000Z", source: "generated by the test" },
  };
  const approved = [sha(canonicalize(record))];
  const buyerBinding = withTestApproval(approved, () => bindTp1Fixture({ record, local: RPC_A }));
  const sellerBinding = withTestApproval(approved, () => bindTp1Fixture({ record, local: RPC_B }));
  return { buyer, seller, session, other, buyerBinding, sellerBinding };
}
type World = ReturnType<typeof world>;

const code = async (fn: () => unknown) => {
  try { await fn(); return "ok"; } catch (error) { if (error instanceof WireError) return error.code; if (error instanceof TypeError) return "TypeError"; throw error; }
};

const buyerSigns = (w: World, now: number, change: Record<string, unknown> = {}) => signWireRequest({
  signer: w.buyer, binding: w.buyerBinding, local: RPC_A, path: "/dacs/v1/payments", jobId: JOB, text: TEXT, seller: w.seller.claim,
  job: { listingPin: PIN, agreementHash: AGREEMENT, profile: w.buyerBinding.profile }, now, ...change,
} as Parameters<typeof signWireRequest>[0]);

function sellerCheck(w: World, header: string, now: number, change: Partial<RequestCheck> = {}, requireDelegation = false) {
  const opened = openWireEnvelope(header, "request", { binding: w.sellerBinding, local: RPC_B, purchaseProfile: w.sellerBinding.profile, requireDelegation });
  return { opened, check: () => checkWireRequest(opened, {
    reserveRequest: () => true, artifacts: agreementFixture(opened), retained: retainedFixture(opened), seller: w.seller.claim, listingPin: PIN,
    method: "POST", path: opened.payload.path, rawBody: Buffer.from(TEXT), now, binding: w.sellerBinding, local: RPC_B,
    purchaseProfile: w.sellerBinding.profile, requireDelegation, ...change,
  }) };
}

const sellerAnswers = (w: World, request: WireRequestPayload, sellerNow: number, change: Record<string, unknown> = {}) =>
  signWireResponse(request, 200, ANSWER, { signer: w.seller, binding: w.sellerBinding, local: RPC_B, now: sellerNow, purchaseProfile: w.sellerBinding.profile, ...change });

const buyerVerifies = (w: World, request: WireRequestPayload, header: string, buyerNow: number) =>
  verifyWireResponse(request, { header, status: 200, body: Buffer.from(ANSWER), now: buyerNow, binding: w.buyerBinding, local: RPC_A });

describe("a seller answer under clock difference (the buyer's 60 s window, the seller's 30 s lifetime)", () => {
  // At 5429154 the seller signed 60 s answers into a 60 s window: any lead refused every answer after the seller's effect.
  it.each([60, 1000, 29_999])("a seller clock %i ms ahead of the buyer's: the request and its default answer are accepted", async (lead) => {
    const w = world();
    const { payload, header: request } = await buyerSigns(w, NOW);
    expect(sellerCheck(w, request, NOW + lead).check().readbackOnly).toBe(false);
    const header = await sellerAnswers(w, payload, NOW + lead);
    const receipt = buyerVerifies(w, payload, header, NOW);
    expect(receipt.body).toEqual({ status: "committed" });
  });

  it.each([60, 1000, 29_999])("a seller clock %i ms behind the buyer's: its default answer is accepted", async (lag) => {
    const w = world();
    const { payload } = await buyerSigns(w, NOW);
    expect(buyerVerifies(w, payload, await sellerAnswers(w, payload, NOW - lag), NOW).body).toEqual({ status: "committed" });
  });

  it("a seller clock up to 30 s ahead passes and one more than 30 s ahead or behind is refused, the documented bound", async () => {
    const w = world();
    const { payload } = await buyerSigns(w, NOW);
    expect(buyerVerifies(w, payload, await sellerAnswers(w, payload, NOW + 30_000), NOW).body).toEqual({ status: "committed" });
    expect(await code(async () => buyerVerifies(w, payload, await sellerAnswers(w, payload, NOW + 30_001), NOW))).toBe("peer_response_mismatch");
    expect(await code(async () => buyerVerifies(w, payload, await sellerAnswers(w, payload, NOW - 30_000), NOW))).toBe("peer_response_mismatch");
  });

  it("an answer lifetime is at most 30 s, and the request window is not an answer setting", async () => {
    const w = world();
    const { payload } = await buyerSigns(w, NOW);
    const expiresAt = async (change: Record<string, unknown>) => (JSON.parse(Buffer.from(await sellerAnswers(w, payload, NOW, change), "base64url").toString("utf8")) as { payload: { expiresAt: number } }).payload.expiresAt;
    expect(await expiresAt({})).toBe(NOW + DACS_SELLER_HTTP_LIMITS.maxSignedLifetimeMs);
    expect(await expiresAt({ lifetimeMs: 5_000 })).toBe(NOW + 5_000);
    expect(await code(() => sellerAnswers(w, payload, NOW, { lifetimeMs: 30_001 }))).toBe("seller_configuration_invalid");
    expect(await code(() => sellerAnswers(w, payload, NOW, { lifetimeMs: 60_000 }))).toBe("seller_configuration_invalid");
    expect(await code(() => sellerAnswers(w, payload, NOW, { maxLifetimeMs: 60_000 }))).toBe("seller_configuration_invalid");
  });
});

describe("a buyer request under clock difference (the seller's 60 s window, the buyer's 30 s lifetime)", () => {
  it.each([1000, 30_000])("a buyer clock %i ms ahead of the seller's: its default request is accepted", async (lead) => {
    const w = world();
    expect(sellerCheck(w, (await buyerSigns(w, NOW + lead)).header, NOW).check()).toEqual({ body: { jobId: JOB }, readbackOnly: false });
  });

  it("a buyer lifetime above 30 s is refused before signing", async () => {
    const w = world();
    expect(await code(() => buyerSigns(w, NOW, { lifetimeMs: 30_001 }))).toBe("TypeError");
    expect(await code(() => buyerSigns(w, NOW, { lifetimeMs: 60_000 }))).toBe("TypeError");
    expect((await buyerSigns(w, NOW, { lifetimeMs: 30_000 })).payload.expiresAt).toBe(NOW + 30_000);
  });
});

describe("the replay journal's retention under clock difference", () => {
  it("each reservation names retainUntil, expiresAt plus the skew allowance", async () => {
    const w = world();
    const { header, payload } = await buyerSigns(w, NOW);
    const seen: WireRequestReservation[] = [];
    sellerCheck(w, header, NOW, { reserveRequest: (r) => { seen.push(r); return true; } }).check();
    expect(seen).toHaveLength(1);
    expect(seen[0]).toEqual({ key: expect.any(String), requestHash: expect.any(String), expiresAt: payload.expiresAt, retainUntil: payload.expiresAt + DACS_SELLER_HTTP_LIMITS.maxClockSkewMs });
    expect(Object.isFrozen(seen[0])).toBe(true);
  });

  it("a journal 30 s ahead of a worker, keeping keys until retainUntil by its own clock, refuses a replay the worker still accepts", async () => {
    const w = world();
    const { header, payload } = await buyerSigns(w, NOW);
    const journal = new Map<string, number>();
    const journalAhead = DACS_SELLER_HTTP_LIMITS.maxClockSkewMs;
    const journalFor = (workerNow: number) => (r: WireRequestReservation) => {
      const journalNow = workerNow + journalAhead;
      for (const [key, until] of journal) if (journalNow >= until) journal.delete(key);
      if (journal.has(r.key)) return false;
      journal.set(r.key, r.retainUntil);
      return true;
    };
    expect(sellerCheck(w, header, NOW, { reserveRequest: journalFor(NOW) }).check().readbackOnly).toBe(false);
    // The worker's last accepting instant: its clock is still before expiresAt, the journal's is 30 s past it.
    const last = payload.expiresAt - 1;
    expect(await code(() => sellerCheck(w, header, last, { reserveRequest: journalFor(last) }).check())).toBe("peer_request_replayed");
    expect(await code(() => sellerCheck(w, header, payload.expiresAt, { reserveRequest: journalFor(payload.expiresAt) }).check())).toBe("peer_expired");
  });
});

describe("a direct request and the host's retained Agreement", () => {
  const artifact = (opened: ReturnType<typeof sellerCheck>["opened"], change: Record<string, unknown>) => [{ ...agreementFixture(opened)[0], ...change }];

  it.each([
    ["another buyer", (w: World) => ({ parties: [{ role: "buyer", primaryClaim: w.other.claim }, { role: "seller", primaryClaim: w.seller.claim }] })],
    ["another seller", (w: World) => ({ parties: [{ role: "buyer", primaryClaim: w.buyer.claim }, { role: "seller", primaryClaim: w.other.claim }] })],
    ["no parties", () => ({ parties: [] })],
    ["another job", () => ({ jobId: OTHER_JOB })],
    ["another Listing", () => ({ listingRef: { ...PIN, version: 2 } })],
  ])("refuses a direct request when the retained Agreement names %s, before reservation", async (_name, change) => {
    const w = world();
    const { header } = await buyerSigns(w, NOW);
    let reserved = 0;
    const { opened } = sellerCheck(w, header, NOW);
    const run = sellerCheck(w, header, NOW, { artifacts: artifact(opened, change(w)), reserveRequest: () => { reserved += 1; return true; } });
    expect(await code(run.check)).toBe("peer_agreement_party_mismatch");
    expect(reserved).toBe(0);
  });

  it("accepts a direct request whose retained Agreement names its own parties, in any order, and one with no artifacts", async () => {
    const w = world();
    const { header } = await buyerSigns(w, NOW);
    const { opened } = sellerCheck(w, header, NOW);
    const parties = [{ role: "seller", primaryClaim: w.seller.claim }, { role: "buyer", primaryClaim: w.buyer.claim }];
    expect(sellerCheck(w, header, NOW, { artifacts: artifact(opened, { parties }) }).check().readbackOnly).toBe(false);
    expect(sellerCheck(w, header, NOW, { artifacts: undefined }).check().readbackOnly).toBe(false);
  });
});
