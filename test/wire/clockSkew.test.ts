function party(seed?: number): WireSigner & { raw: string } {
  const { privateKey, publicKey } = ed25519KeyPair(seed);
  const raw = publicKey.export({ format: "der", type: "spki" }).subarray(-32).toString("hex");
  const signer = { claim: `did:demos:agent:${raw}`, sign: (bytes: Uint8Array) => new Uint8Array(sign(null, Buffer.from(bytes), privateKey)) };
  registerDiscoverySigner(signer);
  return { ...signer, raw };
}

/** SYNTHETIC test-only identity record; not the approved record, not a Demos chain identity. */
async function world() {
  const buyer = party(), seller = party(SELLER_SEED), session = party(), other = party();
  const record = {
    format: "dacs-testnet-identity-record/v1", recordId: "synthetic-test-only/clock-skew", network: "demos-testnet",
    chainIdentity: sha(`SYNTHETIC/clock-skew/${Math.random()}`), pinVersion: "synthetic-test-only/1",
    provenance: { approvedBy: "SYNTHETIC test", approvedAt: "2026-10-14T12:00:00.000Z", source: "generated by the test" },
  };
  const approved = [sha(canonicalize(record))];
  const buyerBinding = (await withTestApproval(approved, async () => (await bindTp1Fixture({ record, local: RPC_A }))));
  const sellerBinding = (await withTestApproval(approved, async () => (await bindTp1Fixture({ record, local: RPC_B }))));
  // The job's finalized commitment and its signed Agreement, which the seller read itself: its payment route needs them.
  const { agreement, agreementHash } = signedAgreement({ buyer, seller, jobId: JOB, listingPin: PIN, generatedAt: NOW - 3_660_000 });
  const commitment = wireCommitment({ seller, buyer: buyer.claim, jobId: JOB, agreementHash, listingPin: PIN, committedAt: NOW - 3_600_000 });
  return { buyer, seller, session, other, buyerBinding, sellerBinding, commitment, agreement, agreementHash };
}
type World = Awaited<ReturnType<typeof world>>;

const code = async (fn: () => unknown) => {
  try { await fn(); return "ok"; } catch (error) { if (error instanceof WireError) return error.code; if (error instanceof TypeError) return "TypeError"; throw error; }
};

const buyerSigns = (w: World, now: number, change: Record<string, unknown> = {}) => signWireRequest({
  signer: w.buyer, binding: w.buyerBinding, local: RPC_A, path: "/dacs/v1/payments", jobId: JOB, text: TEXT, seller: w.seller.claim,
  job: { listingPin: PIN, agreementHash: w.agreementHash, profile: w.buyerBinding.profile }, now,
  commitment: received(w.commitment), agreement: received(w.agreement), signedListing: received(LISTING), ...change,
} as Parameters<typeof signWireRequest>[0]);

async function sellerCheck(w: World, header: string, now: number, change: Partial<RequestCheck> = {}, requireDelegation = false) {
  const opened = (await openWireEnvelope(header, "request", { binding: w.sellerBinding, local: RPC_B, purchaseProfile: w.sellerBinding.profile, requireDelegation }));
  return { opened, check: async () => (await checkWireRequest(opened, {
    requestJournal: testJournal(), artifacts: agreementFixture(opened), retained: retainedFixture(opened), seller: w.seller.claim, listingPin: PIN,
    method: "POST", path: opened.payload.path, rawBody: Buffer.from(TEXT), now, binding: w.sellerBinding, local: RPC_B,
    purchaseProfile: w.sellerBinding.profile, requireDelegation, commitment: received(w.commitment), agreement: received(w.agreement), readCommitmentReceipt: Object.assign(() => "valid", { chainIdentity: w.sellerBinding.profile.chainIdentity }), signedListing: received(LISTING), ...change,
  })) };
}

const sellerAnswers = (w: World, request: WireRequestPayload, sellerNow: number, change: Record<string, unknown> = {}) =>
  signWireResponse(request, 200, ANSWER, { signer: w.seller, binding: w.sellerBinding, local: RPC_B, now: sellerNow, purchaseProfile: w.sellerBinding.profile, ...change });

const buyerVerifies = async (w: World, request: WireRequestPayload, header: string, buyerNow: number) =>
  (await verifyWireResponse(request, { header, status: 200, body: Buffer.from(ANSWER), now: buyerNow, binding: w.buyerBinding, local: RPC_A }));

const delegate = (w: World, notBefore: number, expiresAt: number) => signSellerSessionDelegation({
  version: "1", kind: "seller-session-delegation", buyer: w.buyer.claim, sessionPublicKey: w.session.raw, seller: w.seller.claim,
  listingPin: PIN, jobId: JOB, notBefore, expiresAt, profile: w.buyerBinding.profile,
}, w.buyer, w.buyerBinding, RPC_A);

describe("a delegation's expiry under clock difference", () => {
  // At a5dac90 the buyer chose readback by its own clock and the seller refused it by its own until its clock caught up.
  it("a read route is answered as readback when the buyer's clock passed the expiry and the seller's has not; an effect is still refused", async () => {
    const w = (await world());
    const delegation = await delegate(w, NOW - 3_600_000, NOW);
    const buyerNow = NOW + 1_000, sellerNow = buyerNow - 5_000;
    for (const path of ["/dacs/v1/agreements/state", "/dacs/v1/bundles/buyer-copy"]) {
      const { header } = await buyerSigns(w, buyerNow, { signer: w.session, delegation, path });
      expect((await (await sellerCheck(w, header, sellerNow, {}, true)).check())).toEqual({ body: { jobId: JOB }, readbackOnly: true, effect: null });
    }
    const journals = testJournals();
    const { header } = await buyerSigns(w, buyerNow, { signer: w.session, delegation });
    expect(await code(async () => (await (await sellerCheck(w, header, sellerNow, { requestJournal: journals.open() }, true)).check()))).toBe("peer_delegation_expired");
    expect(journals.reservations()).toHaveLength(0);
  });
});

describe("a delegation sent to a seller that does not require one", () => {
  // At a5dac90 such a seller refused it as peer_envelope_invalid, the code of a corrupt header: a buyer had to guess the setting.
  it("is verified and bound like any delegation: live it may start an effect, expired it reaches read routes only", async () => {
    const w = (await world());
    const live = await delegate(w, NOW - 1_000, NOW + 60_000);
    const { header } = await buyerSigns(w, NOW, { signer: w.session, delegation: live });
    const direct = (await sellerCheck(w, header, NOW));
    expect(direct.opened.delegation?.payload.buyer).toBe(w.buyer.claim);
    expect((await direct.check()).readbackOnly).toBe(false);
    expect(await code(async () => (await (await sellerCheck(w, header, NOW, { artifacts: [] })).check()))).toBe("peer_delegation_agreement_required");
    const expired = await delegate(w, NOW - 3_600_000, NOW - 1);
    const effect = await buyerSigns(w, NOW, { signer: w.session, delegation: expired });
    expect(await code(async () => (await (await sellerCheck(w, effect.header, NOW)).check()))).toBe("peer_delegation_expired");
    const read = await buyerSigns(w, NOW, { signer: w.session, delegation: expired, path: "/dacs/v1/agreements/state" });
    expect((await (await sellerCheck(w, read.header, NOW)).check()).readbackOnly).toBe(true);
    // A request the session key signs without its delegation names the session key as buyer: the host's record refuses it.
    // The buyer's own gate refuses it, so the header is signed by hand to reach the host.
    const barePayload = { ...(await buyerSigns(w, NOW, { signer: w.session, delegation: live })).payload, buyer: w.session.claim };
    const bare = { header: Buffer.from(canonicalize({ payload: barePayload,
      signature: Buffer.from(await w.session.sign(Buffer.from(DACS_SELLER_HTTP_DOMAINS.request + canonicalize(barePayload)))).toString("base64url") })).toString("base64url") };
    const hostRecord = { jobId: JOB, agreementHash: w.agreementHash, buyer: w.buyer.claim, seller: w.seller.claim };
    expect(await code(async () => (await (await sellerCheck(w, bare.header, NOW, { retained: hostRecord, artifacts: [] })).check()))).toBe("peer_agreement_party_mismatch");
  });
});

describe("a host's own input faults are blamed on the host, never on the counterparty", () => {
  const fault = async (fn: () => unknown) => {
    try { await fn(); return "ok"; } catch (error) { if (error instanceof WireError) return [error.code, error.status, error.category]; throw error; }
  };
  it("its kept tuple, its own answer status and its own retained request", async () => {
    const w = (await world());
    const otherTuple = { ...w.sellerBinding.profile, pinVersion: "synthetic-test-only/other" };
    const { payload, header } = await buyerSigns(w, NOW);
    const own = ["tp1_purchase_profile_mismatch", 500, "permanent"];
    expect(await fault(async () => (await openWireEnvelope(header, "request", { binding: w.sellerBinding, local: RPC_B, purchaseProfile: otherTuple })))).toEqual(own);
    expect(await fault(async () => (await (await sellerCheck(w, header, NOW, { purchaseProfile: otherTuple })).check()))).toEqual(own);
    expect(await fault(async () => (await verifyWireResponse({ ...payload, profile: otherTuple }, { header: "x", status: 200, body: Buffer.from(ANSWER), now: NOW, binding: w.buyerBinding, local: RPC_A })))).toEqual(own);
    expect(await fault(() => signWireResponse(payload, 600, ANSWER, { signer: w.seller, binding: w.sellerBinding, local: RPC_B, now: NOW, purchaseProfile: w.sellerBinding.profile })))
      .toEqual(["peer_envelope_invalid", 500, "permanent"]);
    // A peer's malformed header is still the peer's fault.
    expect(await fault(async () => (await openWireEnvelope("A".repeat(10), "request", { binding: w.sellerBinding, local: RPC_B, purchaseProfile: null }))))
      .toEqual(["wire_json_rejected", 401, "counterparty"]);
  });
});

describe("a seller answer under clock difference (the buyer's 60 s window, the seller's 30 s lifetime)", () => {
  // At 5429154 the seller signed 60 s answers into a 60 s window: any lead refused every answer after the seller's effect.
  it.each([60, 1000, 29_999])("a seller clock %i ms ahead of the buyer's: the request and its default answer are accepted", async (lead) => {
    const w = (await world());
    const { payload, header: request } = await buyerSigns(w, NOW);
    expect((await (await sellerCheck(w, request, NOW + lead)).check()).readbackOnly).toBe(false);
    const header = await sellerAnswers(w, payload, NOW + lead);
    const receipt = (await buyerVerifies(w, payload, header, NOW));
    expect(receipt.body).toEqual({ status: "committed" });
  });

  it.each([60, 1000, 29_999])("a seller clock %i ms behind the buyer's: its default answer is accepted", async (lag) => {
    const w = (await world());
    const { payload } = await buyerSigns(w, NOW);
    expect((await buyerVerifies(w, payload, await sellerAnswers(w, payload, NOW - lag), NOW)).body).toEqual({ status: "committed" });
  });

  it("a seller clock up to 30 s ahead passes and one more than 30 s ahead or behind is refused, the documented bound", async () => {
    const w = (await world());
    const { payload } = await buyerSigns(w, NOW);
    expect((await buyerVerifies(w, payload, await sellerAnswers(w, payload, NOW + 30_000), NOW)).body).toEqual({ status: "committed" });
    expect(await code(async () => (await buyerVerifies(w, payload, await sellerAnswers(w, payload, NOW + 30_001), NOW)))).toBe("peer_response_mismatch");
    expect(await code(async () => (await buyerVerifies(w, payload, await sellerAnswers(w, payload, NOW - 30_000), NOW)))).toBe("peer_response_mismatch");
  });

  it("an answer lifetime is at most 30 s, and the request window is not an answer setting", async () => {
    const w = (await world());
    const { payload } = await buyerSigns(w, NOW);
    const expiresAt = async (change: Record<string, unknown>) => (JSON.parse(Buffer.from(await sellerAnswers(w, payload, NOW, change), "base64url").toString("utf8")) as { payload: { expiresAt: number } }).payload.expiresAt;
    expect(await expiresAt({})).toBe(NOW + DACS_SELLER_HTTP_LIMITS.maxSignedLifetimeMs);
    expect(await expiresAt({ lifetimeMs: 5_000 })).toBe(NOW + 5_000);
    expect(await code(() => sellerAnswers(w, payload, NOW, { lifetimeMs: 30_001 }))).toBe("seller_configuration_invalid");
    expect(await code(() => sellerAnswers(w, payload, NOW, { lifetimeMs: 60_000 }))).toBe("seller_configuration_invalid");
    expect(await code(() => sellerAnswers(w, payload, NOW, { maxLifetimeMs: 60_000 }))).toBe("seller_configuration_invalid");
  });
});

describe("a buyer request under clock difference (the seller's 60 s window, the buyer's 30 s lifetime)", () => {
  it.each([1000, 30_000])("a buyer clock %i ms ahead of the seller's: its default request is accepted", async (lead) => {
    const w = (await world());
    expect((await (await sellerCheck(w, (await buyerSigns(w, NOW + lead)).header, NOW)).check())).toEqual({ body: { jobId: JOB }, readbackOnly: false, effect: expect.objectContaining({ state: "new" }) });
  });

  it("a buyer lifetime above 30 s is refused before signing", async () => {
    const w = (await world());
    expect(await code(() => buyerSigns(w, NOW, { lifetimeMs: 30_001 }))).toBe("TypeError");
    expect(await code(() => buyerSigns(w, NOW, { lifetimeMs: 60_000 }))).toBe("TypeError");
    expect((await buyerSigns(w, NOW, { lifetimeMs: 30_000 })).payload.expiresAt).toBe(NOW + 30_000);
  });

  it.each([0, 1])("a request with 1 ms left checks expiry after %i ms of receipt verification", async (elapsed) => {
    const w = await world();
    const { header, payload } = await buyerSigns(w, NOW);
    const journals = testJournals();
    const readCommitmentReceipt = Object.assign(() => {
      vi.mocked(performance.now).mockReturnValue(elapsed);
      return "valid";
    }, { chainIdentity: w.sellerBinding.profile.chainIdentity });
    const checked = await sellerCheck(w, header, payload.expiresAt - 1, { requestJournal: journals.open(), readCommitmentReceipt });
    expect(await code(checked.check)).toBe(elapsed === 0 ? "ok" : "peer_expired");
    expect(journals.reservations()).toHaveLength(elapsed === 0 ? 1 : 0);
  });
});

describe("the replay journal's retention under clock difference", () => {
  it("each reservation names its nonce key, its operation and its request hash", async () => {
    const w = (await world());
    const { header, payload } = await buyerSigns(w, NOW);
    const directory = journalDirectory();
    (await (await sellerCheck(w, header, NOW, { requestJournal: openJournal(directory) })).check());
    // The binding is the operation's first {profile, buyer, agreementHash}: a later request under another one is refused.
    const { profile, buyer, agreementHash } = payload;
    expect(reservationsIn(directory)).toEqual([{ key: expect.any(String), operationId: wireOperationId(payload),
      binding: sha256Hex(canonicalize({ profile, buyer, agreementHash })), requestHash: wireRequestHash(payload) }]);
  });

  it("a journal 30 s ahead of a worker never drops a key: a replay the worker still accepts by its clock is refused", async () => {
    const w = (await world());
    const { header, payload } = await buyerSigns(w, NOW);
    const directory = journalDirectory();
    const ahead = { clock: () => NOW + DACS_SELLER_HTTP_LIMITS.maxClockSkewMs };
    expect((await (await sellerCheck(w, header, NOW, { requestJournal: openJournal(directory, ahead) })).check()).readbackOnly).toBe(false);
    // The worker's last accepting instant: its clock is still before expiresAt.
    const last = payload.expiresAt - 1;
    expect(await code(async () => (await (await sellerCheck(w, header, last, { requestJournal: openJournal(directory, ahead) })).check()))).toBe("peer_request_replayed");
    expect(await code(async () => (await (await sellerCheck(w, header, payload.expiresAt, { requestJournal: openJournal(directory, ahead) })).check()))).toBe("peer_expired");
    expect(reservationsIn(directory)).toHaveLength(1);
  });
});

describe("a direct request and the host's retained Agreement", () => {
  const artifact = (opened: Awaited<ReturnType<typeof sellerCheck>>["opened"], change: Record<string, unknown>) => [{ ...agreementFixture(opened)[0], ...change }];

  it.each([
    ["another buyer", (w: World) => ({ parties: [{ role: "buyer", primaryClaim: w.other.claim }, { role: "seller", primaryClaim: w.seller.claim }] })],
    ["another seller", (w: World) => ({ parties: [{ role: "buyer", primaryClaim: w.buyer.claim }, { role: "seller", primaryClaim: w.other.claim }] })],
    ["no parties", () => ({ parties: [] })],
    ["another job", () => ({ jobId: OTHER_JOB })],
    ["another Listing", () => ({ listingRef: { ...PIN, version: 2 } })],
  ])("refuses a direct request when the retained Agreement names %s, before reservation", async (_name, change) => {
    const w = (await world());
    const { header } = await buyerSigns(w, NOW);
    const journals = testJournals();
    const { opened } = (await sellerCheck(w, header, NOW));
    const run = (await sellerCheck(w, header, NOW, { artifacts: artifact(opened, change(w)), requestJournal: journals.open() }));
    expect(await code(run.check)).toBe("peer_agreement_party_mismatch");
    expect(journals.reservations()).toHaveLength(0);
  });

  it("accepts a direct request whose retained Agreement names its own parties, in any order, and one with no artifacts", async () => {
    const w = (await world());
    const { header } = await buyerSigns(w, NOW);
    const { opened } = (await sellerCheck(w, header, NOW));
    const parties = [{ role: "seller", primaryClaim: w.seller.claim }, { role: "buyer", primaryClaim: w.buyer.claim }];
    expect((await (await sellerCheck(w, header, NOW, { artifacts: artifact(opened, { parties }) })).check()).readbackOnly).toBe(false);
    expect((await (await sellerCheck(w, header, NOW, { artifacts: undefined })).check()).readbackOnly).toBe(false);
  });
});
