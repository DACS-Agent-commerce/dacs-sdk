// Network identity gate with instrumented signers and transports. Missing
// pins, the fixture identity used as a live pin and non-approved identities
// (including a mocked mainnet identity labelled "testnet", with no refused list
// from the caller) produce zero signatures and zero transport sends on every
// wire signing entry point this package has: signWireRequest,
// sellerSessionDelegationSigningBytes, signSellerSessionDelegation,
// signWireResponse and signDiscoveryDocument. The retained seller, browser and
// stdio effect adapters that will call them are not in this package yet. Every
// verification entry point (openWireEnvelope, checkWireRequest,
// verifySellerSessionDelegation, verifyWireResponse, verifyEndpointProof,
// assertPeerProfile) refuses a forged binding and, except assertPeerProfile,
// a changed connection, before it returns anything. The seller opens no request
// and signs no answer, and the generic signWireEnvelope signs nothing, unless
// the tuple kept for the purchase is given and exactly the binding's. The
// public bindTp1Profile approves only by the SDK's own list (the dated approval is pinned
// in source); a caller's list approves nothing. Every identity record here is
// SYNTHETIC and test-only, approved only through the test approval list
// (./testApproval.ts), which replaces src/wire/approval.ts in this file. No
// test reaches any network: every endpoint is under .invalid and fetch is
// replaced by a counter that fails the test if called.
