#!/usr/bin/env node
// The standalone browser provider is the maintained source for these pure routines.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export function payloadHelpersSource(provider) {
  const names = ['EmbeddedWalletError', 'sha256HexOfText', 'anchorJson', 'isPlainObject',
    'nativePayloadDigest', 'hasKeys', 'storageConfirmationShapeMatches'];
  const declarations = names.map(name => {
    const declaration = provider.match(new RegExp(`^(?:export )?(?:async )?(?:class|function) ${name}\\b[\\s\\S]*?^\\}`, 'm'))?.[0]
      ?? provider.match(new RegExp(`^const ${name} = .+;$`, 'm'))?.[0];
    if (!declaration) throw new Error(`provider declaration missing: ${name}`);
    return name === 'isPlainObject' || declaration.startsWith('export ') ? declaration : `export ${declaration}`;
  });
  return '// Generated by scripts/generate-payload-helpers.mjs from the standalone provider.\n'
    + '// Edit sdk-provider.mjs, then regenerate; no provider code is imported at runtime.\n'
    + declarations.join('\n\n') + '\n';
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const provider = readFileSync(new URL('../src/public/portal/embedded-wallet/sdk-provider.mjs', import.meta.url), 'utf8');
  writeFileSync(new URL('../src/wallet/payload-helpers.mjs', import.meta.url), payloadHelpersSource(provider));
}
