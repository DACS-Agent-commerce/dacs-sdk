#!/usr/bin/env node
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { publicationJson, publicationText } from './publication-text.mjs';
import { sourceGit } from './source-git.mjs';
export const root = join(dirname(fileURLToPath(import.meta.url)), '../../..');
export const pkg = join(root, 'packages/dacs-client');
export const prefix = 'packages/dacs-client/';
export const PUBLICATION_HEAD = 'aac03055bdbeabc7c0771642d99f0c4baf7e3de9';
export const BASELINE = '5c7d5e066eed8ebf9b9744b7a44e6cee72abe7f1';
export const HISTORY_SHA256 = '4170f296835330141c4eff81bd548468f16fd1dde0000cc83ccbe6f67d3c9a00';
export const git = (...args) => sourceGit(['-C', root, ...args], {encoding:'utf8', maxBuffer:1<<28, stdio:['ignore','pipe','pipe']}).trimEnd();
export const blob = bytes => createHash('sha1').update(`blob ${bytes.length}\0`).update(bytes).digest('hex');
export const localBlob = path => existsSync(join(root,path)) ? blob(readFileSync(join(root,path))) : null;
// Coordinates come from Git's baseline-to-current hunks. Metadata starts at
// line 1; deleted paths have no current coordinate. Avoid self-referential
// generated-document hunks while locating every changed source/test range.
export function locations(path) {
  if (!/^packages\/dacs-client\/(?:src|test)\//.test(path)) return `\`${path}:1\``;
  if (!existsSync(join(root, path))) return `\`${path}\` (deleted)`;
  const diff = git('diff', '--no-renames', '--unified=0', BASELINE, '--', path);
  const starts = [...new Set([...diff.matchAll(/^@@ -[0-9,]+ \+(\d+)(?:,\d+)? @@/gm)].map(m => Math.max(1, Number(m[1]))))];
  return (starts.length ? starts : [1]).map(line => `\`${path}:${line}\``).join(', ');
}
export const ledger = () => JSON.parse(readFileSync(join(pkg,'DELTA-LEDGER.json'),'utf8'));
export function commits() {
  return git('log','--no-merges','--reverse','--format=%H%x09%s',BASELINE+'..HEAD').split('\n').filter(Boolean).map(row => { const at=row.indexOf('\t'); return {sha:row.slice(0,at),subject:row.slice(at+1)}; });
}
export function table(data = ledger()) {
  const files=JSON.parse(readFileSync(join(pkg,'PROVENANCE.json'),'utf8')).files;
  const history=commits();
  const coordinates = new Map();
  const locate = path => { if (!coordinates.has(path)) coordinates.set(path, locations(path)); return coordinates.get(path); };
  const lines=['<!-- generated by scripts/delta-map.mjs; do not edit -->', readFileSync(join(pkg,'DELTA-NOTES.md'),'utf8').trim(), '', '## Commit register', '', '| Delta | Exact commit subject | Resolved commit |', '|---|---|---|'];
  for(const change of data.changes) {
    const found=history.filter(c=>c.subject===change.subject);
    lines.push(`| ${change.delta} | ${change.subject} | Git subject selector (must resolve exactly once after publication checkpoint) |`);
    for(const f of change.files) lines.push(`| | ${locate(f.path)} | ${f.after===null?'deleted':f.after} |`);
  }
  if (data.mergeSnapshots?.length) {
    lines.push('', '## Reviewed merge snapshots', '', '| Merge | Parents | File | Parent blobs | Merged blob |', '|---|---|---|---|---|');
    for (const snapshot of data.mergeSnapshots) for (const file of snapshot.files) {
      lines.push(`| ${snapshot.commit} | ${snapshot.parents.join(', ')} | ${locate(file.path)} | ${file.parentBlobs.join(', ')} | ${file.after} |`);
    }
  }
  const inventory=JSON.parse(readFileSync(join(pkg,'DELTA-COMMITS.json'),'utf8'));
  lines.push('', '## Complete commit and file inventory', '', 'Full hashes below bind completed commits. Unhashed record commits use unique exact subjects to avoid self-referential hashes. Source/test coordinates are generated from baseline-to-current Git hunks, so they name changed ranges at the current head; metadata starts at line 1 and deletions are explicit. The delta sections explain the reason for each group.', '', '| Commit / exact selector | Touched file:line |', '|---|---|');
  for(const c of inventory) for(const path of c.files) lines.push(`| ${c.sha??c.subject} | ${locate(path)} |`);
  lines.push('', '## Original moved files', '', '| Destination | Source path | Blob at publication checkpoint | Status | Current blob |', '|---|---|---|---|---|');
  for(const f of files) {
    const changes=data.changes.filter(c=>c.files.some(x=>x.path===f.path));
    const current=localBlob(f.path);
    let source='deleted before publication';try{source=git('rev-parse',`${BASELINE}:${f.path}`);}catch{}
    lines.push(`| \`${f.path}\` | \`${f.sourcePath}\` | ${source} | ${changes.length?`${current?'changed':'deleted'} by ${[...new Set(changes.map(c=>c.delta))].join(', ')}`:'unchanged'} | ${current??'deleted'} |`);
  }
  return publicationText(lines.join('\n')+'\n');
}
// Source records form a DAG. A merge may choose a recorded parent blob;
// synthesizing a different blob requires its own immutable commit/parent pins.
function terminalBlobs(data, history, failures) {
  const graph = new Map(git('rev-list', '--parents', BASELINE+'..HEAD').split('\n').map(row => { const [sha,...parents]=row.split(' '); return [sha,parents]; }));
  const ancestors = new Map();
  function before(a,b) {
    if (!ancestors.has(b)) {
      const found = new Set(), pending = [...(graph.get(b) ?? [])];
      while (pending.length) { const sha=pending.pop(); if (found.has(sha)) continue; found.add(sha); pending.push(...(graph.get(sha) ?? [])); }
      ancestors.set(b,found);
    }
    return ancestors.get(b).has(a);
  }
  const events = new Map(), add = (sha,file) => {
    const rows=events.get(file.path) ?? []; rows.push({sha,after:file.after}); events.set(file.path,rows);
  };
  for (const change of data.changes) {
    const matches=history.filter(row=>row.subject===change.subject);
    if (matches.length===1) for (const file of change.files) add(matches[0].sha,file);
  }
  const seen = new Set(), at = (rev,path) => { try { return git('rev-parse','--verify',`${rev}:${path}`); } catch { return null; } };
  for (const snapshot of data.mergeSnapshots ?? []) {
    const refuse = () => failures.push(`invalid merge snapshot ${snapshot.commit}`);
    if (seen.has(snapshot.commit)) failures.push(`duplicate merge snapshot ${snapshot.commit}`);
    seen.add(snapshot.commit);
    if (!/^[0-9a-f]{40}$/.test(snapshot.commit) || !graph.has(snapshot.commit)
      || !Array.isArray(snapshot.parents) || snapshot.parents.length!==2
      || JSON.stringify(snapshot.parents)!==JSON.stringify(graph.get(snapshot.commit))
      || !Array.isArray(snapshot.files) || snapshot.files.length===0) { refuse(); continue; }
    const paths = new Set();
    for (const file of snapshot.files) {
      if (typeof file.path!=='string' || !/^packages\/dacs-client\/(src|test)\//.test(file.path)
        || file.path.split('/').some(part=>['','.','..'].includes(part)) || paths.has(file.path)
        || JSON.stringify(file.parentBlobs)!==JSON.stringify(snapshot.parents.map(parent=>at(parent,file.path)))
        || file.after!==at(snapshot.commit,file.path) || file.parentBlobs.includes(file.after)) { refuse(); continue; }
      paths.add(file.path); add(snapshot.commit,file);
    }
  }
  return new Map([...events].map(([path,rows]) => [path,rows.filter(row=>!rows.some(other=>before(row.sha,other.sha))).map(row=>row.after)]));
}
export function checkDeltas(packageDir=pkg) {
  const failures=[]; const data=ledger(); const history=commits();
  const archived=readFileSync(join(pkg,'evidence/publication-history.json'));
  if(createHash('sha256').update(archived).digest('hex')!==HISTORY_SHA256) failures.push('archived source/delta evidence digest differs');
  const evidence=JSON.parse(archived);
  for(const [name,key] of [['PROVENANCE.json','sourceManifest'],['DELTA-LEDGER.json','deltas'],['DELTA-COMMITS.json','commits']]) {
    const shipped=JSON.parse(git('show',`${BASELINE}:${prefix}${name}`));
    if(JSON.stringify(shipped)!==JSON.stringify(evidence[key])) failures.push(`${name}: archived evidence differs from immutable publication`);
  }
  const historical=new Map();
  for(const change of evidence.deltas.changes) for(const file of change.files) {
    if(historical.has(file.path)&&historical.get(file.path)!==file.before) failures.push(`${file.path}: archived delta chain is discontinuous`);
    historical.set(file.path,file.after);
  }
  for(const [path,want] of historical) {
    let shipped=null;try{shipped=git('rev-parse','--verify',`${BASELINE}:${path}`);}catch{}
    if(shipped!==want) failures.push(`${path}: archived delta terminal differs from immutable publication`);
  }
  const sourceManifest=evidence.sourceManifest;
  if(JSON.stringify(sourceManifest)!==JSON.stringify(JSON.parse(readFileSync(join(pkg,'PROVENANCE.json'))))) failures.push('source manifest differs from archived source/delta evidence');
  if(data.schema!=='dacs-client-deltas/v2'||data.baseline!==BASELINE) failures.push('delta ledger baseline/schema changed');
  const subjects=new Set();
  for(const c of data.changes) {
    if(subjects.has(c.subject)) failures.push(`duplicate delta subject ${c.subject}`);
    subjects.add(c.subject);
    if(!['D10','D9','D1','D11','D15','D16'].includes(c.delta)||!(c.subject.startsWith(`delta(client): ${c.delta} `)||(c.delta==='D11'&&c.subject.startsWith('fix(client): D11 ')))) failures.push(`invalid delta ${c.subject}`);
    const matches=history.filter(h=>h.subject===c.subject);
    if(matches.length!==1) failures.push(`delta commit selector must resolve once: ${c.subject}`);
    if(matches.length===1) {
      const sha=matches[0].sha;
      for(const f of c.files) {
        for(const [rev,want] of [[`${sha}^`,f.before],[sha,f.after]]) {
          let actual=null;try{actual=git('rev-parse','--verify',`${rev}:${f.path}`);}catch{}
          if(actual!==want) failures.push(`${f.path}: delta ${c.delta} blob differs at ${rev}`);
        }
      }
    }
  }
  const inventory=JSON.parse(readFileSync(join(pkg,'DELTA-COMMITS.json'),'utf8'));
  for(const h of history) {
    const item=inventory.find(c=>c.subject===h.subject);
    const files=git('diff','--no-renames','--name-only',h.sha+'^',h.sha).split('\n').filter(Boolean).sort();
    // The published inventory remains auditable. Later unrelated SDK work
    // does not require a client control update; merges are excluded above.
    let published=false;try{git('merge-base','--is-ancestor',h.sha,PUBLICATION_HEAD);published=true;}catch{}
    if(!published&&!files.some(path=>path.startsWith(prefix)))continue;
    if(!item || (item.sha!==null && item.sha!==h.sha) || JSON.stringify([...item.files].sort())!==JSON.stringify(files)) failures.push(`complete commit/file inventory differs for ${h.sha}`);
  }
  const terminals=terminalBlobs(data,history,failures);
  const originals=JSON.parse(readFileSync(join(pkg,'PROVENANCE.json'),'utf8')).files.map(f=>f.path);
  const allowed=new Set([...originals,...evidence.deltas.changes.flatMap(c=>c.files.map(f=>f.path)),...data.changes.flatMap(c=>c.files.map(f=>f.path)),...terminals.keys()]);
  for(const h of history) {
    const changed=git('diff','--no-renames','--name-only',h.sha+'^',h.sha,'--',prefix+'src',prefix+'test').split('\n').filter(Boolean);
    const record=data.changes.find(c=>c.subject===h.subject);
    for(const path of changed) if(!record?.files.some(f=>f.path===path)) failures.push(`${path}: unenumerated change in ${h.sha}`);
  }
  // A staged edit remains a change even when its working file is restored.
  // Compare object identities directly, including deletions and mode changes.
  const indexRows=git('ls-files','--stage','--',prefix+'src',prefix+'test').split('\n').filter(Boolean);
  const headRows=git('ls-tree','-r','HEAD','--',prefix+'src',prefix+'test').split('\n').filter(Boolean);
  const staged=new Map(indexRows.map(row=>{const [meta,path]=row.split('\t');const [mode,hash,stage]=meta.split(' ');return [path,{mode,hash,stage}];}));
  const committed=new Map(headRows.map(row=>{const [meta,path]=row.split('\t');const [mode,,hash]=meta.split(' ');return [path,{mode,hash}];}));
  for(const path of new Set([...committed.keys(),...staged.keys()])){
    const a=staged.get(path),b=committed.get(path);
    if(!a||!b||a.stage!=='0'||a.mode!==b.mode||a.hash!==b.hash)failures.push(`${path}: index differs from HEAD for moved source/test`);
  }
  for(const path of allowed) {
    let expected=terminals.get(path);
    if(!expected) { let baseline=null;try{baseline=git('rev-parse','--verify',`${BASELINE}:${path}`);}catch{} expected=[baseline]; }
    const rel=path.slice(prefix.length); const local=join(packageDir,rel);
    const actual=existsSync(local)?blob(readFileSync(local)):null;
    const selected = committed.get(path)?.hash ?? null;
    if(!expected.includes(selected) || actual!==selected) failures.push(`${path}: current blob differs from enumerated deltas (working bytes must equal HEAD)`);
  }
  if(readFileSync(join(pkg,'DELTA-MAP.md'),'utf8')!==table(data)) failures.push('DELTA-MAP.md differs from generated Git table (run delta-map.mjs)');
  return {failures,allowed};
}
if(process.argv[1]===fileURLToPath(import.meta.url)) {
  if(process.argv[2]==='--record') {
    const [delta,...words]=process.argv.slice(3); const subject=words.join(' '); const data=ledger();
    const paths=git('diff','--cached','--no-renames','--name-only','--',prefix+'src',prefix+'test').split('\n').filter(Boolean);
    if(!paths.length) throw new Error('stage moved/new source and tests first');
    data.changes.push({delta,subject,files:paths.map(path=>{let before=null;try{before=git('rev-parse','--verify',`HEAD:${path}`);}catch{}return {path,before,after:localBlob(path)};})});
    writeFileSync(join(pkg,'DELTA-LEDGER.json'),publicationJson(data));
  }
  writeFileSync(join(pkg,'DELTA-MAP.md'),table());
}
