#!/usr/bin/env node
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { publicationJson, publicationText } from './publication-text.mjs';
import { sourceGit } from './source-git.mjs';
export const root = join(dirname(fileURLToPath(import.meta.url)), '../../..');
export const pkg = join(root, 'packages/dacs-client');
export const prefix = 'packages/dacs-client/';
export const BASELINE = 'ecb2cd76cdb00f44b0ca05c4cead2774bae0f064';
export const git = (...args) => sourceGit(['-C', root, ...args], {encoding:'utf8', maxBuffer:1<<28, stdio:['ignore','pipe','pipe']}).trimEnd();
export const blob = bytes => createHash('sha1').update(`blob ${bytes.length}\0`).update(bytes).digest('hex');
export const localBlob = path => existsSync(join(root,path)) ? blob(readFileSync(join(root,path))) : null;
// Coordinates come from Git's baseline-to-current hunks. Metadata starts at
// line 1; deleted paths have no current coordinate. Avoid self-referential
// generated-document hunks while locating every changed source/test range.
export function locations(path) {
  if (!existsSync(join(root, path))) return `\`${path}\` (deleted)`;
  if (!/^(?:packages\/dacs-client\/(?:src|test)\/|src\/)/.test(path)) return `\`${path}:1\``;
  const diff = git('diff', '--no-renames', '--unified=0', BASELINE, '--', path);
  const starts = [...new Set([...diff.matchAll(/^@@ -[0-9,]+ \+(\d+)(?:,\d+)? @@/gm)].map(m => Math.max(1, Number(m[1]))))];
  return (starts.length ? starts : [1]).map(line => `\`${path}:${line}\``).join(', ');
}
export const ledger = () => JSON.parse(readFileSync(join(pkg,'DELTA-LEDGER.json'),'utf8'));
export function commits() {
  return git('log','--reverse','--format=%H%x09%s',BASELINE+'..HEAD').split('\n').filter(Boolean).map(row => { const at=row.indexOf('\t'); return {sha:row.slice(0,at),subject:row.slice(at+1)}; });
}
export function table(data = ledger()) {
  const files=JSON.parse(readFileSync(join(pkg,'PROVENANCE.json'),'utf8')).files;
  const history=commits();
  const coordinates = new Map();
  const locate = path => { if (!coordinates.has(path)) coordinates.set(path, locations(path)); return coordinates.get(path); };
  const lines=['<!-- generated by scripts/delta-map.mjs; do not edit -->', readFileSync(join(pkg,'DELTA-NOTES.md'),'utf8').trim(), '', '## Commit register', '', '| Delta | Exact commit subject | Resolved commit |', '|---|---|---|'];
  for(const change of data.changes) {
    const found=history.filter(c=>c.subject===change.subject);
    lines.push(`| ${change.delta} | ${change.subject} | Git subject selector (must resolve exactly once) |`);
    for(const f of change.files) lines.push(`| | ${locate(f.path)} | ${f.after===null?'deleted':f.after} |`);
  }
  const inventory=JSON.parse(readFileSync(join(pkg,'DELTA-COMMITS.json'),'utf8'));
  lines.push('', '## Complete commit and file inventory', '', 'Full hashes below bind completed commits. Unhashed record commits use unique exact subjects to avoid self-referential hashes. Source/test coordinates are generated from baseline-to-current Git hunks, so they name changed ranges at the current head; metadata starts at line 1 and deletions are explicit. The delta sections explain the reason for each group.', '', '| Commit / exact selector | Touched file:line |', '|---|---|');
  for(const c of inventory) for(const path of c.files) lines.push(`| ${c.sha??c.subject} | ${locate(path)} |`);
  lines.push('', '## Original moved files', '', '| Destination | Source path | Source blob at step 1 | Status | Current blob |', '|---|---|---|---|---|');
  for(const f of files) {
    const changes=data.changes.filter(c=>c.files.some(x=>x.path===f.path));
    const current=localBlob(f.path);
    const source=git('rev-parse',`${BASELINE}:${f.path}`);
    lines.push(`| \`${f.path}\` | \`${f.sourcePath}\` | ${source} | ${changes.length?`${current?'changed':'deleted'} by ${[...new Set(changes.map(c=>c.delta))].join(', ')}`:'unchanged'} | ${current??'deleted'} |`);
  }
  return publicationText(lines.join('\n')+'\n');
}
export function checkDeltas(packageDir=pkg) {
  const failures=[]; const data=ledger(); const history=commits();
  if(data.schema!=='dacs-client-deltas/v1'||data.baseline!=='ecb2cd7') failures.push('delta ledger baseline/schema changed');
  const subjects=new Set();
  for(const c of data.changes) {
    if(subjects.has(c.subject)) failures.push(`duplicate delta subject ${c.subject}`);
    subjects.add(c.subject);
    if(!['D10','D9','D1','D15'].includes(c.delta)||!c.subject.startsWith(`delta(client): ${c.delta} `)) failures.push(`invalid delta ${c.subject}`);
    const matches=history.filter(h=>h.subject===c.subject);
    if(matches.length!==1) failures.push(`delta commit selector must resolve once: ${c.subject}`);
    if(matches.length===1) {
      const sha=matches[0].sha;
      for(const f of c.files) {
        for(const [rev,want] of [[`${sha}^`,f.before],[sha,f.after]]) {
          let actual=null;try{actual=git('rev-parse','--verify',`${rev}:${f.path}`);}catch{}
          if(actual!==want) failures.push(`${f.path}: delta ${c.delta} blob differs at ${rev}`);
        }
      }
    }
  }
  const inventory=JSON.parse(readFileSync(join(pkg,'DELTA-COMMITS.json'),'utf8'));
  for(const h of history) {
    const item=inventory.find(c=>c.subject===h.subject);
    const files=git('diff','--no-renames','--name-only',h.sha+'^',h.sha).split('\n').filter(Boolean).sort();
    if(!item || (item.sha!==null && item.sha!==h.sha) || JSON.stringify([...item.files].sort())!==JSON.stringify(files)) failures.push(`complete commit/file inventory differs for ${h.sha}`);
  }
  const originals=JSON.parse(readFileSync(join(pkg,'PROVENANCE.json'),'utf8')).files.map(f=>f.path);
  const allowed=new Set([...originals,...data.changes.flatMap(c=>c.files.map(f=>f.path))]);
  for(const h of history) {
    const changed=git('diff','--no-renames','--name-only',h.sha+'^',h.sha,'--',prefix+'src',prefix+'test').split('\n').filter(Boolean);
    const record=data.changes.find(c=>c.subject===h.subject);
    for(const path of changed) if(!record?.files.some(f=>f.path===path)) failures.push(`${path}: unenumerated change in ${h.sha}`);
  }
  // A staged edit remains a change even when its working file is restored.
  // Compare object identities directly, including deletions and mode changes.
  const indexRows=git('ls-files','--stage','--',prefix+'src',prefix+'test').split('\n').filter(Boolean);
  const headRows=git('ls-tree','-r','HEAD','--',prefix+'src',prefix+'test').split('\n').filter(Boolean);
  const staged=new Map(indexRows.map(row=>{const [meta,path]=row.split('\t');const [mode,hash,stage]=meta.split(' ');return [path,{mode,hash,stage}];}));
  const committed=new Map(headRows.map(row=>{const [meta,path]=row.split('\t');const [mode,,hash]=meta.split(' ');return [path,{mode,hash}];}));
  for(const path of new Set([...committed.keys(),...staged.keys()])){
    const a=staged.get(path),b=committed.get(path);
    if(!a||!b||a.stage!=='0'||a.mode!==b.mode||a.hash!==b.hash)failures.push(`${path}: index differs from HEAD for moved source/test`);
  }
  for(const path of allowed) {
    const changes=data.changes.flatMap(c=>c.files.filter(f=>f.path===path));
    const expected=changes.length?changes.at(-1).after:git('rev-parse',`${BASELINE}:${path}`);
    const rel=path.slice(prefix.length); const local=join(packageDir,rel);
    const actual=existsSync(local)?blob(readFileSync(local)):null;
    if(actual!==expected) failures.push(`${path}: current blob differs from enumerated deltas`);
  }
  if(readFileSync(join(pkg,'DELTA-MAP.md'),'utf8')!==table(data)) failures.push('DELTA-MAP.md differs from generated Git table (run delta-map.mjs)');
  return {failures,allowed};
}
if(process.argv[1]===fileURLToPath(import.meta.url)) {
  if(process.argv[2]==='--record') {
    const [delta,...words]=process.argv.slice(3); const subject=words.join(' '); const data=ledger();
    const paths=git('diff','--cached','--no-renames','--name-only','--',prefix+'src',prefix+'test').split('\n').filter(Boolean);
    if(!paths.length) throw new Error('stage moved/new source and tests first');
    data.changes.push({delta,subject,files:paths.map(path=>{let before=null;try{before=git('rev-parse','--verify',`HEAD:${path}`);}catch{}return {path,before,after:localBlob(path)};})});
    writeFileSync(join(pkg,'DELTA-LEDGER.json'),publicationJson(data));
  }
  writeFileSync(join(pkg,'DELTA-MAP.md'),table());
}
